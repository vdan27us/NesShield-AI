
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

from sklearn.ensemble import RandomForestClassifier
from sklearn.dummy import DummyClassifier
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    roc_auc_score,
)
from sklearn.model_selection import train_test_split
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler


SEED = 42
N_SCENARIOS = 12_000
rng = np.random.default_rng(SEED)


def generate_synthetic_data(n=N_SCENARIOS):
    """Generate illustrative scenarios, not real business observations."""

    starting_balance = rng.uniform(2_000, 30_000, n)
    expected_inflows = rng.uniform(0, 15_000, n)
    scheduled_outflows = rng.uniform(0, 25_000, n)
    inflow_delay_days = rng.integers(0, 8, n)
    outflow_uplift = rng.uniform(0, 0.25, n)
    other_expenses = rng.uniform(0, 5_000, n)

    # Illustrative stress model: delayed inflows are excluded from
    # available cash during the seven-day forecast.
    inflows_received = np.where(
        inflow_delay_days <= 2, expected_inflows, 0
    )

    stressed_outflows = scheduled_outflows * (1 + outflow_uplift)

    projected_min_balance = (
        starting_balance
        + inflows_received
        - stressed_outflows
        - other_expenses
    )

    # Label is generated by this explicit rule.
    shortfall = (projected_min_balance < 0).astype(int)

    data = pd.DataFrame({
        "starting_balance": starting_balance,
        "expected_inflows": expected_inflows,
        "scheduled_outflows": scheduled_outflows,
        "inflow_delay_days": inflow_delay_days,
        "outflow_uplift": outflow_uplift,
        "other_expenses": other_expenses,
        "projected_min_balance": projected_min_balance,
        "shortfall": shortfall,
    })

    return data


def main():
    data = generate_synthetic_data()

    feature_columns = [
        "starting_balance",
        "expected_inflows",
        "scheduled_outflows",
        "inflow_delay_days",
        "outflow_uplift",
        "other_expenses",
    ]

    X = data[feature_columns]
    y = data["shortfall"]

    X_train, X_test, y_train, y_test = train_test_split(
        X,
        y,
        test_size=0.2,
        random_state=SEED,
        stratify=y,
    )

    model = RandomForestClassifier(
        n_estimators=250,
        max_depth=10,
        min_samples_leaf=5,
        class_weight="balanced",
        random_state=SEED,
        n_jobs=-1,
    )
    model.fit(X_train, y_train)

    predictions = model.predict(X_test)
    probabilities = model.predict_proba(X_test)[:, 1]

    baseline = DummyClassifier(strategy="most_frequent")
    baseline.fit(X_train, y_train)
    baseline_predictions = baseline.predict(X_test)

    print("\n=== CashGuard AI: Synthetic ML Evaluation ===")
    print("Dataset: synthetic, generated from explicit assumptions")
    print("Scenarios:", len(data))
    print("Positive shortfall rate:", round(float(y.mean()), 4))

    print("\nRandom Forest")
    print("Accuracy:", round(accuracy_score(y_test, predictions), 4))
    print("ROC AUC:", round(roc_auc_score(y_test, probabilities), 4))
    print("Confusion matrix:")
    print(confusion_matrix(y_test, predictions))
    print(classification_report(y_test, predictions, zero_division=0))

    print("Majority-class baseline accuracy:",
          round(accuracy_score(y_test, baseline_predictions), 4))

    model_dir = Path("backend/ml")
    model_dir.mkdir(parents=True, exist_ok=True)

    model_path = model_dir / "risk_model.joblib"
    joblib.dump(
        {
            "model": model,
            "features": feature_columns,
            "target": "shortfall",
            "dataset_type": "synthetic",
            "seed": SEED,
        },
        model_path,
    )

    data_path = model_dir / "synthetic_cashflow_data.csv"
    data.to_csv(data_path, index=False)

    print("\nSaved model:", model_path)
    print("Saved dataset:", data_path)


if __name__ == "__main__":
    main()
